-- The retention sweep's unread rule, `read_at IS NULL AND created_at < now() - 90 days` (SCRUM-1224, lib/notification-retention.ts).
-- Before this, no index on "notifications" led with "created_at", so every batch of the sweep scanned the whole table.
-- Also `@@index([created_at])` in schema.prisma, so a db push database has it too.
--
-- CONCURRENTLY, alone in its file and not wrapped: it cannot run inside a transaction, and a plain CREATE INDEX would
-- hold every bell write in the product for the length of a scan of the whole table (__tests__/migration-tx.test.ts).
-- If it fails, Prisma records the migration as failed and every later deploy stops (P3009) until it is resolved, and
-- the failed build can leave an INVALID "notifications_created_at_idx" that IF NOT EXISTS would skip on a retry. Recovery is an ops step,
-- not a new migration (no later migration runs while this one is failed): `DROP INDEX CONCURRENTLY IF EXISTS
-- "notifications_created_at_idx";`, then `prisma migrate resolve --rolled-back` for this folder, then redeploy. Afterwards
-- `SELECT indisvalid FROM pg_index WHERE indexrelid = '"notifications_created_at_idx"'::regclass` reads true.
CREATE INDEX CONCURRENTLY IF NOT EXISTS "notifications_created_at_idx" ON "notifications" ("created_at");
